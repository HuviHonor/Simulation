class Graph {

    private final int vertices;
    private final int edges;

    public Graph(int vertices, int edges) {
        this.vertices = vertices;
        this.edges = edges;
    }

    public int getVertices() {
        return vertices;
    }

    public int getEdges() {
        return edges;
    }

}
